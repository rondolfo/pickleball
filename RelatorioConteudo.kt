    private fun t(idioma: String, chave: String): String =
        TEXTOS[idioma]?.get(chave) ?: TEXTOS["en"]?.get(chave) ?: chave

    private fun esc(s: String): String = s
        .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;")

