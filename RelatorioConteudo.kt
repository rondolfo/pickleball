    fun montar(todas: List<Partida>, jogadores: List<Jogador>, idioma: String): String {
        val validas = EstatisticasJogador.validas(todas)
        val curto = { id: String ->
            jogadores.firstOrNull { it.id == id }?.curto ?: "?"
        }

        if (validas.isEmpty()) {
            return pagina(idioma, "<section><p class=\"vazio\">" +
                esc(t(idioma, "sem_dados")) + "</p></section>")
        }

        val (regulares, visitantes) = EstatisticasJogador.rankingDividido(
            todas, jogadores, EstatisticasJogador.MINIMO_REGULAR
        )
        val corpo = StringBuilder()

        corpo.append(cabecalho(idioma, validas, regulares.size + visitantes.size))
        corpo.append(kpis(idioma, validas))
        corpo.append(secaoRanking(idioma, regulares, curto))
        corpo.append(secaoSaldo(idioma, regulares, curto))
        corpo.append(secaoConfrontos(idioma, todas, regulares, curto))
        corpo.append(secaoDuplas(idioma, todas, curto))
        corpo.append(secaoSessoes(idioma, todas))
        corpo.append(secaoTabela(idioma, regulares, visitantes, curto))
        corpo.append(secaoDestaques(idioma, validas, regulares, todas, curto))
        corpo.append(secaoDados(idioma, todas.size, validas.size))

        return pagina(idioma, corpo.toString())
    }

    private fun cabecalho(idioma: String, validas: List<Partida>, nJogadores: Int): String {
        val fmt = SimpleDateFormat(
            if (idioma == "pt") "dd/MM/yyyy" else "MMM d, yyyy",
            if (idioma == "pt") Locale("pt", "BR") else Locale.US
        )
        val inicio = fmt.format(Date(validas.minOf { it.inicio }))
        val fim = fmt.format(Date(validas.maxOf { it.inicio }))
        val sessoes = EstatisticasJogador.porSessao(validas).size
        return """<header><h1>${esc(t(idioma, "titulo"))}</h1>
          <p class="sub">$inicio ${t(idioma, "ate")} $fim &middot; ${validas.size}
          ${t(idioma, "jogos")} $sessoes ${t(idioma, "sessoes")} &middot;
          $nJogadores ${t(idioma, "jogadores")}</p></header>"""
    }

    private fun kpis(idioma: String, validas: List<Partida>): String {
        val stats = validas.map { it.estatisticas() }
        val rallies = stats.sumOf { it.totalRallies }
        val pontos = stats.sumOf { it.pontosEsquerda + it.pontosDireita }
        val dias = EstatisticasJogador.porSessao(validas).size
        val itens = listOf(
            validas.size.toString() to t(idioma, "kpi_jogos"),
            dias.toString() to t(idioma, "kpi_dias"),
            rallies.toString() to t(idioma, "kpi_rallies"),
            pontos.toString() to t(idioma, "kpi_pontos"),
            (rallies / max(1, validas.size)).toString() to t(idioma, "kpi_media")
        )
        return itens.joinToString("", "<div class=\"kpis\">", "</div>") { (v, r) ->
            "<div class=\"kpi\"><div class=\"v\">$v</div><div class=\"r\">${esc(r)}</div></div>"
        }
    }

    private fun secaoRanking(
        idioma: String,
        regulares: List<ResumoJogador>,
        curto: (String) -> String
    ): String {
        if (regulares.isEmpty()) return ""
        val podio = regulares.take(3).mapIndexed { i, r ->
            val pos = t(idioma, listOf("primeiro", "segundo", "terceiro")[i])
            """<div class="p ${if (i == 0) "ouro" else ""}">
                 <div class="pos">$pos</div>
                 <div class="n">${esc(curto(r.id))}</div>
                 <div class="d">${r.vitorias} ${t(idioma, "vitorias_em")} ${r.partidas} ${t(idioma, "partidas")}</div>
                 <div class="pct">${r.aproveitamento}%</div></div>"""
        }.joinToString("", "<div class=\"podio\">", "</div>")

        val grafico = barras(
            regulares.map { Barra(curto(it.id), it.aproveitamento.toDouble(), "${it.aproveitamento}%") },
            teto = 100.0, divergente = false, padL = 96.0, padR = 60.0, sufixo = "%"
        )
        val leg = String.format(t(idioma, "l_rank"), EstatisticasJogador.MINIMO_REGULAR)
        return secao(t(idioma, "h_rank"), leg, podio + grafico)
    }

    private fun secaoSaldo(
        idioma: String,
        regulares: List<ResumoJogador>,
        curto: (String) -> String
    ): String {
        if (regulares.isEmpty()) return ""
        val ordenado = regulares.sortedByDescending { it.saldo }
        val grafico = barras(
            ordenado.map {
                Barra(curto(it.id), it.saldo.toDouble(), (if (it.saldo > 0) "+" else "") + it.saldo)
            },
            teto = null, divergente = true, padL = 96.0, padR = 54.0, sufixo = ""
        )
        return secao(t(idioma, "h_saldo"), t(idioma, "l_saldo"), grafico)
    }

    private fun secaoDuplas(
        idioma: String,
        todas: List<Partida>,
        curto: (String) -> String
    ): String {
        val duplas = EstatisticasJogador.duplas(todas).take(8)
        if (duplas.isEmpty()) return ""
        val grafico = barras(
            duplas.map {
                Barra(
                    curto(it.a) + " & " + curto(it.b),
                    it.aproveitamento.toDouble(),
                    "${it.aproveitamento}%  (${it.jogos})"
                )
            },
            teto = 100.0, divergente = false, padL = 158.0, padR = 78.0, sufixo = "%"
        )
        val leg = String.format(t(idioma, "l_duplas"), EstatisticasJogador.MINIMO_DUPLA)
        return secao(t(idioma, "h_duplas"), leg, grafico)
    }

    private fun secaoConfrontos(
        idioma: String,
        todas: List<Partida>,
        regulares: List<ResumoJogador>,
        curto: (String) -> String
    ): String {
        if (regulares.size < 2) return ""
        val mapa = EstatisticasJogador.confrontos(todas)
        val ids = regulares.map { it.id }
        val n = ids.size

        val sb = StringBuilder()
        sb.append("<div class=\"grid-h\" style=\"grid-template-columns:110px repeat($n,minmax(54px,1fr))\">")
        sb.append("<div></div>")
        ids.forEach { sb.append("<div class=\"cab\">${esc(curto(it))}</div>") }

        ids.forEach { a ->
            sb.append("<div class=\"cabl\">${esc(curto(a))}</div>")
            ids.forEach { b ->
                val c = if (a == b) null else mapa[a to b]
                if (c == null || c.jogos == 0) {
                    sb.append("<div class=\"cel vazio\">.</div>")
                } else {
                    val taxa = c.vitorias.toDouble() / c.jogos
                    val forca = min(0.5, abs(taxa - 0.5) * 1.1)
                    val fundo = when {
                        abs(taxa - 0.5) < 0.06 -> "var(--neutro)"
                        taxa > 0.5 -> "color-mix(in oklab, var(--azul) ${(forca * 100).roundToInt()}%, var(--sup))"
                        else -> "color-mix(in oklab, var(--vermelho) ${(forca * 100).roundToInt()}%, var(--sup))"
                    }
                    val dica = "${esc(curto(a))} / ${esc(curto(b))}: ${c.vitorias}-${c.jogos - c.vitorias}"
                    sb.append("<div class=\"cel\" data-t=\"$dica\" style=\"background:$fundo\">" +
                        "${c.vitorias}-${c.jogos - c.vitorias}</div>")
                }
            }
        }
        sb.append("</div>")
        sb.append("""<div class="marcas">
            <span class="marca"><span class="pt" style="background:var(--azul)"></span> ${esc(t(idioma, "vantagem"))}</span>
            <span class="marca"><span class="pt" style="background:var(--neutro);border:1px solid var(--eixo)"></span> ${esc(t(idioma, "equilibrio"))}</span>
            <span class="marca"><span class="pt" style="background:var(--vermelho)"></span> ${esc(t(idioma, "trails"))}</span>
            </div>""")
        return secao(t(idioma, "h_h2h"), t(idioma, "l_h2h"), sb.toString())
    }

    private fun secaoSessoes(idioma: String, todas: List<Partida>): String {
        val sessoes = EstatisticasJogador.porSessao(todas)
        if (sessoes.size < 2) return ""

        val larg = 760.0; val alt = 230.0
        val padL = 34.0; val padR = 14.0; val padT = 12.0; val padB = 44.0
        val pw = larg - padL - padR; val ph = alt - padT - padB
        val teto = max(1, sessoes.maxOf { it.second }).toDouble()
        val px = { i: Int -> padL + (i.toDouble() / max(1, sessoes.size - 1)) * pw }
        val py = { v: Int -> padT + ph - (v / teto) * ph }

        val sb = StringBuilder("<svg viewBox=\"0 0 ${larg.toInt()} ${alt.toInt()}\" role=\"img\">")
        var g = 0
        while (g <= teto.toInt()) {
            sb.append("<line class=\"gl\" x1=\"$padL\" y1=\"${py(g)}\" x2=\"${larg - padR}\" y2=\"${py(g)}\"/>")
            sb.append("<text class=\"tick\" x=\"${padL - 8}\" y=\"${py(g) + 4}\" text-anchor=\"end\">$g</text>")
            g += 2
        }
        sb.append("<polyline fill=\"none\" stroke=\"var(--azul)\" stroke-width=\"2\" stroke-linejoin=\"round\" points=\"")
        sessoes.forEachIndexed { i, (_, v) -> sb.append("${px(i)},${py(v)} ") }
        sb.append("\"/>")
        sessoes.forEachIndexed { i, (dia, v) ->
            sb.append("<circle data-t=\"$dia: $v\" cx=\"${px(i)}\" cy=\"${py(v)}\" r=\"4.5\" " +
                "fill=\"var(--azul)\" stroke=\"var(--sup)\" stroke-width=\"2\"/>")
            if (i % 3 == 0 || i == sessoes.size - 1) {
                val rot = dia.substring(5)
                sb.append("<text class=\"tick\" x=\"${px(i)}\" y=\"${alt - 22}\" text-anchor=\"middle\" " +
                    "transform=\"rotate(-42 ${px(i)} ${alt - 22})\">$rot</text>")
            }
        }
        sb.append("<line class=\"bl\" x1=\"$padL\" y1=\"${padT + ph}\" x2=\"${larg - padR}\" y2=\"${padT + ph}\"/></svg>")
        return secao(t(idioma, "h_sessoes"), t(idioma, "l_sessoes"), sb.toString())
    }

    private fun secaoTabela(
        idioma: String,
        regulares: List<ResumoJogador>,
        visitantes: List<ResumoJogador>,
        curto: (String) -> String
    ): String {
        val cab = listOf("c_jogador", "c_j", "c_v", "c_d", "c_apr", "c_pf", "c_pc",
                         "c_saldo", "c_ppj", "c_seq", "c_parceiro")
            .joinToString("") { "<th>${esc(t(idioma, it))}</th>" }

        val linha = { r: ResumoJogador, visitante: Boolean ->
            val marca = if (visitante)
                " <span style=\"color:var(--mudo);font-size:12px\">${esc(t(idioma, "visitante"))}</span>" else ""
            val parceiro = r.parceiroMaisFrequente?.let { "${esc(curto(it))} (${r.vezesComParceiro})" } ?: "."
            val classe = if (r.saldo >= 0) "pos-n" else "neg-n"
            val sinal = if (r.saldo > 0) "+" else ""
            """<tr><td>${esc(curto(r.id))}$marca</td><td>${r.partidas}</td><td>${r.vitorias}</td>
               <td>${r.derrotas}</td><td>${r.aproveitamento}%</td><td>${r.pontosFeitos}</td>
               <td>${r.pontosSofridos}</td><td class="$classe">$sinal${r.saldo}</td>
               <td>${String.format(Locale.US, "%.1f", r.pontosPorJogo)}</td>
               <td>${r.maiorSequencia}</td><td>$parceiro</td></tr>"""
        }

        val corpo = regulares.joinToString("") { linha(it, false) } +
            visitantes.joinToString("") { linha(it, true) }
        val tabela = "<div style=\"overflow-x:auto\"><table><thead><tr>$cab</tr></thead>" +
            "<tbody>$corpo</tbody></table></div>"
        return secao(t(idioma, "h_tabela"), t(idioma, "l_tabela"), tabela)
    }

    private fun secaoDestaques(
        idioma: String,
        validas: List<Partida>,
        regulares: List<ResumoJogador>,
        todas: List<Partida>,
        curto: (String) -> String
    ): String {
        if (regulares.isEmpty()) return ""
        val stats = validas.map { it.estatisticas() }
        val viradas = stats.sumOf { it.viradas }
        val maisRallies = stats.maxOf { it.totalRallies }
        val topSeq = regulares.maxByOrNull { it.maiorSequencia }!!
        val maisJogos = regulares.maxByOrNull { it.partidas }!!
        val topSaldo = regulares.maxByOrNull { it.saldo }!!
        val melhorDupla = EstatisticasJogador.duplas(todas).firstOrNull()

        val itens = mutableListOf<Pair<String, String>>()
        itens += t(idioma, "d_seq") to
            String.format(t(idioma, "d_seq_v"), topSeq.maiorSequencia, curto(topSeq.id))
        itens += t(idioma, "d_presente") to
            String.format(t(idioma, "d_presente_v"), curto(maisJogos.id), maisJogos.partidas)
        if (melhorDupla != null) {
            itens += t(idioma, "d_dupla") to String.format(
                t(idioma, "d_dupla_v"), curto(melhorDupla.a), curto(melhorDupla.b),
                melhorDupla.aproveitamento, melhorDupla.jogos
            )
        }
        itens += t(idioma, "d_saldo") to String.format(
            t(idioma, "d_saldo_v"), curto(topSaldo.id),
            (if (topSaldo.saldo > 0) "+" else "") + topSaldo.saldo
        )
        itens += t(idioma, "d_rallies") to String.format(t(idioma, "d_rallies_v"), maisRallies)
        itens += t(idioma, "d_viradas") to String.format(t(idioma, "d_viradas_v"), viradas)

        val html = itens.joinToString("", "<div class=\"rec\">", "</div>") { (titulo, conteudo) ->
            "<div><div class=\"t\">${esc(titulo)}</div><div class=\"c\">${esc(conteudo)}</div></div>"
        }
        return secao(t(idioma, "h_destaques"), "", html)
    }

    private fun secaoDados(idioma: String, total: Int, usadas: Int): String {
        val corpo = """<div class="nota">
            <p>${esc(String.format(t(idioma, "nota1"), total, usadas, total - usadas))}</p>
            <p>${esc(String.format(t(idioma, "nota2"), EstatisticasJogador.MINIMO_REGULAR))}</p>
            </div>"""
        return secao(t(idioma, "h_dados"), "", corpo)
    }

    private fun secao(titulo: String, legenda: String, conteudo: String): String {
        val leg = if (legenda.isBlank()) "" else "<p class=\"leg\">${esc(legenda)}</p>"
        return "<section><h2>${esc(titulo)}</h2>$leg$conteudo</section>"
    }

    // ---------- grafico de barras ----------

    private data class Barra(val rotulo: String, val valor: Double, val texto: String)

    private fun barras(
        itens: List<Barra>,
        teto: Double?,
        divergente: Boolean,
        padL: Double,
        padR: Double,
        sufixo: String
    ): String {
        if (itens.isEmpty()) return ""
        val h = 30.0; val gap = 9.0; val topo = 6.0; val baixo = 30.0
        val larg = 760.0; val plot = larg - padL - padR
        val alt = itens.size * (h + gap) + topo + baixo
        val alto = teto ?: itens.maxOf { it.valor }
        val baixoV = if (divergente) min(0.0, itens.minOf { it.valor }) else 0.0
        val faixa = if (alto - baixoV == 0.0) 1.0 else alto - baixoV
        val x = { v: Double -> padL + ((v - baixoV) / faixa) * plot }
        val baseY = alt - baixo + 4

        val sb = StringBuilder("<svg viewBox=\"0 0 ${larg.toInt()} ${alt.toInt()}\" role=\"img\">")
        val zero = x(0.0)
        for (g in 0..4) {
            val gx = padL + (plot * g) / 4
            val gv = baixoV + (faixa * g) / 4
            sb.append("<line class=\"gl\" x1=\"$gx\" y1=\"$topo\" x2=\"$gx\" y2=\"$baseY\"/>")
            sb.append("<text class=\"tick\" x=\"$gx\" y=\"${baseY + 16}\" text-anchor=\"middle\">" +
                "${gv.roundToInt()}$sufixo</text>")
        }
        itens.forEachIndexed { i, it ->
            val y = topo + i * (h + gap)
            val neg = divergente && it.valor < 0
            val x0 = if (neg) x(it.valor) else if (divergente) zero else padL
            val w = max(2.0, abs(x(it.valor) - (if (divergente) zero else padL)))
            val cor = if (neg) "var(--vermelho)" else "var(--azul)"
            sb.append("<text class=\"rot\" x=\"${padL - 10}\" y=\"${y + h / 2 + 4}\" text-anchor=\"end\">" +
                "${esc(it.rotulo)}</text>")
            sb.append("<rect data-t=\"${esc(it.rotulo)}: ${esc(it.texto)}\" x=\"$x0\" y=\"$y\" " +
                "width=\"$w\" height=\"$h\" rx=\"4\" fill=\"$cor\"/>")
            // o valor fica sempre a direita da barra, inclusive nas negativas,
            // senao colide com o nome do jogador do lado esquerdo
            val fim = if (neg) zero + 8 else x0 + w + 8
            sb.append("<text class=\"val\" x=\"$fim\" y=\"${y + h / 2 + 4}\" text-anchor=\"start\">" +
                "${esc(it.texto)}</text>")
        }
        if (divergente) sb.append("<line class=\"bl\" x1=\"$zero\" y1=\"$topo\" x2=\"$zero\" y2=\"$baseY\"/>")
        sb.append("<line class=\"bl\" x1=\"$padL\" y1=\"$baseY\" x2=\"${larg - padR}\" y2=\"$baseY\"/>")
        sb.append("</svg>")
        return sb.toString()
    }

